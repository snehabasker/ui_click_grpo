"""Where do the misses go?  python scripts/analyze_failures.py clean biased
Needs eval jsons that contain per-sample predictions (``preds``). Samples are regenerated from their seeds, so the
true element layout is known and every miss can be classified:

  hit            click inside the target box
  target_extent  inside the target's *own* extent but outside its box (e.g. the text label next to a checkbox)
  other_element  inside a different element's box  -> followed the wrong instruction / confused two elements
  near           within 30 px of the target box, on background  -> localisation error
  far            anywhere else
"""
import json
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

import numpy as np

from uiclick.evaluate import test_samples
from uiclick.reward import parse_click
from uiclick.synth import H, W

CATS = ["hit", "target_extent", "other_element", "near", "far", "unparseable"]


def classify(s, text):
    p = parse_click(text)
    if p is None:
        return "unparseable", None
    x, y = p[0] / 1000 * W, p[1] / 1000 * H
    t = s.elements[s.target]
    bx0, by0, bx1, by1 = t.box
    if bx0 <= x <= bx1 and by0 <= y <= by1:
        return "hit", 0.0
    ex0, ey0 = bx0 - t.box_off[0], by0 - t.box_off[1]
    if ex0 <= x <= ex0 + t.w and ey0 <= y <= ey0 + t.h:
        return "target_extent", None
    for i, e in enumerate(s.elements):
        if i != s.target and e.box[0] <= x <= e.box[2] and e.box[1] <= y <= e.box[3]:
            return "other_element", None
    d = np.hypot(max(bx0 - x, 0, x - bx1), max(by0 - y, 0, y - by1))
    return ("near" if d <= 30 else "far"), d


def pct(c, n):
    return f"{100 * c / n:.0f}%"


out = ["# Failure taxonomy (auto-generated by scripts/analyze_failures.py)\n"]
for name in sys.argv[1:]:
    data = json.loads((ROOT / "results" / f"eval_{name}.json").read_text())
    n = data["n"]
    tot, by_kind = Counter(), defaultdict(Counter)
    for split, conds in data["results"].items():
        if "real" not in conds or "preds" not in conds["real"]:
            continue
        ss = test_samples(split, n)
        for s, t in zip(ss, conds["real"]["preds"]):
            c, _ = classify(s, t)
            tot[c] += 1
            by_kind[s.kind][c] += 1
    N = sum(tot.values())
    if not N:
        out.append(f"## {name}: no per-sample predictions stored\n")
        continue
    out += [f"## {name}  (n = {N} predictions over the cue-isolation splits)\n", "| target type | n | " + " | ".join(CATS) + " |", "|---|---|" + "---|" * len(CATS)]
    for k in sorted(by_kind) + ["ALL"]:
        c = tot if k == "ALL" else by_kind[k]
        m = sum(c.values())
        out.append(f"| {k} | {m} | " + " | ".join(pct(c[x], m) for x in CATS) + " |")
    out.append("")
(ROOT / "results" / "failures.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out))
